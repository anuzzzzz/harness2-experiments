"""h2x-lab: Harvey LAB tasks run by Claude Code in a files workspace (Harness2's own tasks suite).

Tasks are generated by ``h2x lab-import`` into .harness2/tasks/<id>/ with the matter documents in
files/documents/, the full LAB task.json (with its rubric) in check/ -- which Harness2 never
shows to the improver -- and a ``check`` command that grades output/ with ``h2x lab-grade``.
This module only swaps the prompts for legal practitioner ones; execution, workspaces and
grading plumbing are Harness2's GenericAdapter, unchanged.

The prompt text below is adapted from the Harness2 CLI benchmark plugin
(plugins/harness2-benchmarks/harness2_benchmarks/lab.py, Apache-2.0).
"""

from __future__ import annotations

import shutil
from dataclasses import replace

from harness2 import suite as generic
from harness2.core.spec import BenchPrompts
from harness2.registry import SuiteContext

from .common import fake_mode

LAB_PROMPTS = BenchPrompts(
    work=(
        "Professional legal work for a supervising lawyer: analysing matter records, reviewing "
        "and drafting instruments, and preparing research or advice in the exact files "
        "requested. The source documents and instructions control. The result must be "
        "matter-ready: complete, internally consistent, traceable to the record, and usable "
        "by another lawyer without repair."
    ),
    domain_word="practice area",
    deliverable_word="legal deliverable",
    inv_levers=(
        "- inventory the matter files before choosing a reading order; map each requested "
        "output and issue to the sources likely to control it\n"
        "- extract text from binary documents (.docx, .pdf, .xlsx) with a reliable tool, "
        "preserve pinpoint locations, and distinguish unread material from material that says "
        "nothing\n"
        "- establish an output plan early, write every exact requested filename before the "
        "budget is at risk, then reopen each artifact and check that it parses\n"
        "- reconcile names, dates, amounts, defined terms and cross-document conflicts with a "
        "recorded source hierarchy instead of silently choosing one version"
    ),
    dom_levers=(
        "- identify the correct legal work product and the audience-dependent structure it "
        "needs\n"
        "- separate source text, matter fact, legal inference, risk assessment and "
        "recommendation; do not present one as another\n"
        "- test parties, authority, jurisdiction, effective dates, conditions, exceptions, "
        "timing, remedies, definitions and cross-references where they matter to the "
        "assignment\n"
        "- never manufacture a citation, rule or defined term the sources do not support"
    ),
    yardstick=(
        "Did the run identify the controlling matter record, perform the legal operation the "
        "instructions called for, preserve traceability for important propositions, produce "
        "every named file in usable form, and inspect the finished artifact before stopping?"
    ),
    selection_checks=(
        "Prefer the work product that uses the correct instrument or memo form; covers every "
        "requested issue and output; states matter facts, calculations and quoted provisions "
        "consistently with the supplied record; distinguishes uncertainty from conclusion; and "
        "is internally coherent enough for a lawyer to review rather than reconstruct."
    ),
)

DRAFT_LENS = (
    "WORK TYPE -- DRAFT. Confirm the correct instrument, parties, authority and intended legal "
    "effect before drafting. When adapting a precedent, every party name, defined term, "
    "economic term and cross-reference must be carried through or replaced consistently, and "
    "every change the term sheet or instructions require must appear in the operative text. "
    "Check definitions, operative provisions, conditions, exceptions, dates, remedies, exhibits "
    "and signature blocks as applicable. Every clause must fit the matter rather than read like "
    "generic filler."
)


class LabAdapter(generic.GenericAdapter):
    def __init__(self, ctx: SuiteContext):
        super().__init__(ctx)
        self.spec = replace(
            self.spec, name="h2x-lab", prompts=LAB_PROMPTS, domain_word="practice area"
        )

    def prompts_for(self, task_id: str) -> BenchPrompts:
        steer = self.settings.get("improver.steer")
        lens = DRAFT_LENS + (("\n\n" + steer) if steer and not steer.startswith("@") else "")
        return replace(LAB_PROMPTS, domain_guidance=lens)

    def judge_cost(self, run_dir) -> float:
        """What grading this rollout cost (written by h2x lab-grade)."""
        import json
        from pathlib import Path

        try:
            data = json.loads((Path(run_dir) / ".h2x_judge.json").read_text(encoding="utf-8"))
            return float(data.get("judge_cost_usd") or 0.0)
        except (OSError, ValueError):
            return 0.0


def make_adapter(ctx: SuiteContext) -> LabAdapter:
    return LabAdapter(ctx)


def check(ctx: SuiteContext) -> list[str]:
    problems = [] if fake_mode() else list(generic.check(ctx))
    if not fake_mode():
        if shutil.which("pandoc") is None:
            problems.append("pandoc is required to read .docx deliverables (apt-get install pandoc)")
        import importlib.util

        for module in ("anthropic", "docx", "pdfplumber", "markitdown"):
            if importlib.util.find_spec(module) is None:
                problems.append(f"python module {module!r} missing (pip install -r requirements/lab.txt)")
    tasks = generic.list_tasks(ctx.settings.path("paths.tasks"))
    if not tasks:
        problems.append("no LAB tasks imported; run: h2x lab-import e1-lab-lpa")
    return problems
